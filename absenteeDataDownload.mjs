import puppeteer from 'puppeteer-extra';
import StealthPlugin from 'puppeteer-extra-plugin-stealth';
import AdmZip from 'adm-zip';
import fs from 'node:fs';
import path from 'node:path';
import { pipeline } from 'node:stream/promises';

puppeteer.use(StealthPlugin());

const ELECTIONS_FILE = path.resolve('./elections.json');

async function getElectionS3Url(page, election) {
  const targetUrl = election.absenteeUrl;
  console.log(`\n=== Processing [${election.name || election.label || 'Election'}] ===`);
  console.log(`Navigating to: ${targetUrl}`);

  await page.goto(targetUrl, { waitUntil: 'networkidle2', timeout: 45000 });

  // Wait for the S3 download link generated by Salesforce (piercing Shadow DOM)
  console.log('Locating download link...');
  const s3UrlHandle = await page.waitForFunction(() => {
    function queryDeep(root) {
      for (const el of root.querySelectorAll('a')) {
        if (el.href && (el.href.includes('GAVR') || el.href.includes('.zip'))) {
          return el.href;
        }
      }
      for (const el of root.querySelectorAll('*')) {
        if (el.shadowRoot) {
          const found = queryDeep(el.shadowRoot);
          if (found) return found;
        }
      }
      return null;
    }
    return queryDeep(document);
  }, { timeout: 45000 });

  return await s3UrlHandle.jsonValue();
}

async function downloadAndExtract(s3Url, election) {
  const targetDir = path.resolve(election.absenteeFileDir || './data/absentee');
  const extractDir = path.join(targetDir, 'data');
  const destZip = path.join(targetDir, `${election.name || 'absentee'}.zip`);

  fs.mkdirSync(targetDir, { recursive: true });
  fs.mkdirSync(extractDir, { recursive: true });

  console.log(`Streaming download to: ${destZip}...`);
  const response = await fetch(s3Url);
  if (!response.ok) {
    throw new Error(`Failed to download from S3: ${response.status} ${response.statusText}`);
  }

  const fileStream = fs.createWriteStream(destZip);
  await pipeline(response.body, fileStream);

  const downloadedSize = (fs.statSync(destZip).size / (1024 * 1024)).toFixed(2);
  console.log(`Download finished (${downloadedSize} MB).`);

  // Unzip contents to targetDir/data
  console.log(`Extracting ${destZip} to ${extractDir}...`);
  const zip = new AdmZip(destZip);
  zip.extractAllTo(extractDir, true);

  // Remove STATEWIDE.csv if present
  const statewideCsv = path.join(extractDir, 'STATEWIDE.csv');
  if (fs.existsSync(statewideCsv)) {
    fs.unlinkSync(statewideCsv);
    console.log('Removed STATEWIDE.csv');
  }

  console.log(`Successfully completed [${election.name || 'Election'}]!`);
}

async function main() {
  const elections = JSON.parse(fs.readFileSync(ELECTIONS_FILE, 'utf-8'));

  const arg1 = process.argv[2];
  const arg2 = process.argv[3];

  let electionsToDownload = [];

  if (arg1) {
    // If CLI args provided: match by election number, name, or direct URL
    const match = elections.find(
      (e) => e.absenteeElectionNumber === arg1 || e.name === arg1
    );
    if (match) {
      if (arg2) match.absenteeFileDir = arg2;
      electionsToDownload.push(match);
    } else if (arg1.startsWith('http')) {
      electionsToDownload.push({
        name: 'manual_download',
        absenteeUrl: arg1,
        absenteeFileDir: arg2 || './data/absentee'
      });
    } else {
      console.error(`Could not find election matching '${arg1}' in elections.json`);
      process.exit(1);
    }
  } else {
    // No CLI args: find all elections with absenteeDownload: true
    electionsToDownload = elections.filter((e) => e.absenteeDownload === true && e.absenteeUrl);
  }

  if (electionsToDownload.length === 0) {
    console.log('No elections found with absenteeDownload: true (and valid absenteeUrl) in elections.json.');
    return;
  }

  console.log(`Found ${electionsToDownload.length} election(s) to download.`);

  const browser = await puppeteer.launch({
    headless: false,
    args: [
      '--disable-blink-features=AutomationControlled',
      '--no-sandbox',
      '--disable-setuid-sandbox',
      '--window-size=1920,1080'
    ]
  });

  const downloadQueue = [];

  try {
    const page = await browser.newPage();
    for (const election of electionsToDownload) {
      const s3Url = await getElectionS3Url(page, election);
      downloadQueue.push({ s3Url, election });
    }
  } finally {
    // Close browser cleanly - no downloads are active in Chrome!
    await browser.close();
  }

  // Stream downloads directly via Node fetch
  for (const item of downloadQueue) {
    await downloadAndExtract(item.s3Url, item.election);
  }
}

main().catch((err) => {
  console.error('Error:', err);
  process.exit(1);
});


